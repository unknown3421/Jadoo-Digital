$apiLoginUrl = "https://api.jadoodigital.com/api/v2.1/user/auth/login";
$apiRefreshUrl = "https://api.jadoodigital.com/api/v2.1/user/auth/refresh";
$inputFile = "playlist.m3u"; // Input playlist file
$outputFile = "out.m3u";     // Output playlist file
$folder = "Ferdos_Jadoo";
$tokenFile = "$folder/token.cache";

// Credentials
$username = "jadoo6000";
$password = "jadoo6000";
